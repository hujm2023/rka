const (
	retentionSettingKey = "retention"
	retentionLastRunKey = "retention.lastRun"
)

// RetentionPolicy is measured in days. Zero means "keep forever".
type RetentionPolicy struct {
	Tasks   int `json:"tasks"`
	Events  int `json:"events"`
	Audit   int `json:"audit"`
	Backups int `json:"backups"`
	Logs    int `json:"logs"`
}

// DefaultRetentionPolicy exposes the configured defaults for the admin API.
func (s *Service) DefaultRetentionPolicy() RetentionPolicy {
	return RetentionPolicy{
		Tasks:   s.cfg.Retention.TaskDays,
		Events:  s.cfg.Retention.EventDays,
		Audit:   s.cfg.Retention.AuditDays,
		Backups: s.cfg.Retention.BackupDays,
		Logs:    s.cfg.Retention.LogDays,
	}
}

// effectiveRetentionPolicy merges the stored override with configuration
// defaults. It also returns who last changed the policy.
func (s *Service) effectiveRetentionPolicy(ctx context.Context) (RetentionPolicy, any, string) {
	policy := s.DefaultRetentionPolicy()
	var raw []byte
	var updatedAt time.Time
	var updatedBy string
	err := s.db.Pool.QueryRow(ctx, `
		select value, updated_at, coalesce(updated_by::text, '')
		from settings where key = $1`, retentionSettingKey).Scan(&raw, &updatedAt, &updatedBy)
	if err != nil {
		return policy, nil, ""
	}
	if err := json.Unmarshal(raw, &policy); err != nil {
		s.log.Warn("stored retention policy is invalid; using defaults", "error", err)
		return s.DefaultRetentionPolicy(), nil, ""
	}
	return policy, updatedAt.UTC(), updatedBy
}

// RunRetention applies the effective retention policy and returns per-category
// deletion counts. Backup directories are only removed when they lie under
// cfg.BackupDir() and match this package's timestamp naming convention.
func (s *Service) RunRetention(ctx context.Context) (map[string]int, error) {
	policy, _, _ := s.effectiveRetentionPolicy(ctx)
	stats := map[string]int{"tasks": 0, "events": 0, "audit": 0, "backups": 0, "logs": 0}

	if policy.Tasks > 0 {
		tag, err := s.db.Pool.Exec(ctx, `
			delete from ai_tasks
			where status in ('completed', 'failed', 'cancelled')
			  and coalesce(finished_at, created_at) < now() - make_interval(days => $1)`, policy.Tasks)
		if err != nil {
			return stats, fmt.Errorf("清理 AI 任务失败：%w", err)
		}
		stats["tasks"] = int(tag.RowsAffected())
	}
	if policy.Events > 0 {
		tag, err := s.db.Pool.Exec(ctx, `
			delete from ai_events where created_at < now() - make_interval(days => $1)`, policy.Events)
		if err != nil {
			return stats, fmt.Errorf("清理 AI 事件失败：%w", err)
		}
		stats["events"] = int(tag.RowsAffected())
	}
	if policy.Audit > 0 {
		tag, err := s.db.Pool.Exec(ctx, `
			delete from audit_log where created_at < now() - make_interval(days => $1)`, policy.Audit)
		if err != nil {
			return stats, fmt.Errorf("清理审计日志失败：%w", err)
		}
		stats["audit"] = int(tag.RowsAffected())
	}
	if policy.Backups > 0 {
		count, err := s.purgeBackups(ctx, policy.Backups)
		if err != nil {
			return stats, err
		}
		stats["backups"] = count
	}
	if policy.Logs > 0 {
		count, err := s.purgeLogs(policy.Logs)
		if err != nil {
			return stats, err
		}
		stats["logs"] = count
	}

	payload, _ := json.Marshal(map[string]any{"at": time.Now().UTC(), "stats": stats})
	_, _ = s.db.Pool.Exec(ctx, `
		insert into settings (key, value) values ($1, $2::jsonb)
		on conflict (key) do update set value = excluded.value, updated_at = now()`,
		retentionLastRunKey, string(payload))
	return stats, nil
}

func (s *Service) purgeBackups(ctx context.Context, days int) (int, error) {
	rows, err := s.db.Pool.Query(ctx, `
		select id::text, rel_path from backups
		where status <> 'creating'
		  and created_at < now() - make_interval(days => $1)`, days)
	if err != nil {
		return 0, fmt.Errorf("读取过期备份失败：%w", err)
	}
	type staleBackup struct{ ID, RelPath string }
	var stale []staleBackup
	for rows.Next() {
		var item staleBackup
		if err := rows.Scan(&item.ID, &item.RelPath); err != nil {
			rows.Close()
			return 0, err
		}
		stale = append(stale, item)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return 0, err
	}

	deleted := 0
	for _, item := range stale {
		if err := s.removeBackupBatch(item.RelPath); err != nil {
			s.log.Warn("skip retention of unexpected backup path", "rel_path", item.RelPath, "error", err)
			continue
		}
		if _, err := s.db.Pool.Exec(ctx, `delete from backups where id = $1::uuid`, item.ID); err != nil {
			return deleted, fmt.Errorf("删除备份记录失败：%w", err)
		}
		deleted++
	}
	return deleted, nil
}

// removeBackupBatch only ever removes a directory inside cfg.BackupDir() whose
// basename matches the timestamp generated by CreateBackup.
func (s *Service) removeBackupBatch(relPath string) error {
	abs := filepath.Clean(filepath.Join(s.cfg.DataDir, filepath.FromSlash(relPath)))
	root := filepath.Clean(s.cfg.BackupDir())
	if abs == root || !isWithin(root, abs) {
		return fmt.Errorf("路径不在备份目录内：%s", relPath)
	}
	if !backupTimestampPattern.MatchString(filepath.Base(abs)) {
		return fmt.Errorf("目录名不是备份批次时间戳：%s", relPath)
	}
	return os.RemoveAll(abs)
}

func (s *Service) purgeLogs(days int) (int, error) {
	root := s.cfg.LogDir()
	info, err := os.Stat(root)
	if err != nil {
		if os.IsNotExist(err) {
			return 0, nil
		}
		return 0, err
	}
	if !info.IsDir() {
		return 0, nil
	}
	cutoff := time.Now().Add(-time.Duration(days) * 24 * time.Hour)
	removed := 0
	err = filepath.WalkDir(root, func(path string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		fileInfo, err := entry.Info()
		if err != nil {
			return nil
		}
		if fileInfo.ModTime().Before(cutoff) {
			if err := os.Remove(path); err != nil {
				s.log.Warn("remove log file failed", "path", path, "error", err)
				return nil
			}
			removed++
		}
		return nil
	})
	return removed, err
}

// HTTP handlers -------------------------------------------------------------

func (s *Service) retentionResponse(ctx context.Context) map[string]any {
	policy, updatedAt, updatedBy := s.effectiveRetentionPolicy(ctx)
	var lastRun any
	var raw []byte
	if err := s.db.Pool.QueryRow(ctx, `select value from settings where key = $1`, retentionLastRunKey).Scan(&raw); err == nil {
		var decoded map[string]any
		if json.Unmarshal(raw, &decoded) == nil {
			lastRun = decoded
		}
	}
	return map[string]any{
		"policy":    policy,
		"defaults":  s.DefaultRetentionPolicy(),
		"updatedAt": updatedAt,
		"updatedBy": updatedBy,
		"lastRun":   lastRun,
	}
}

func (s *Service) handleGetRetention(w http.ResponseWriter, r *http.Request) {
	httpx.JSON(w, r, http.StatusOK, s.retentionResponse(r.Context()))
}

type retentionRequest struct {
	Tasks   *int `json:"tasks"`
	Events  *int `json:"events"`
	Audit   *int `json:"audit"`
	Backups *int `json:"backups"`
	Logs    *int `json:"logs"`
}

func (s *Service) handlePutRetention(w http.ResponseWriter, r *http.Request) {
	var request retentionRequest
	if err := httpx.Decode(w, r, &request, 8<<10); err != nil {
		httpx.Error(w, r, err)
		return
	}
	policy, _, _ := s.effectiveRetentionPolicy(r.Context())
	apply := func(value *int, name string, target *int) error {
		if value == nil {
			return nil
		}
		if *value < 0 || *value > 3650 {
			return httpx.NewError(http.StatusBadRequest, "invalid_retention", fmt.Sprintf("%s 保留天数必须在 0（永久保留）到 3650 之间。", name))
		}
		*target = *value
		return nil
	}
	if err := apply(request.Tasks, "tasks", &policy.Tasks); err != nil {
		httpx.Error(w, r, err)
		return
	}
	if err := apply(request.Events, "events", &policy.Events); err != nil {
		httpx.Error(w, r, err)
		return
	}
	if err := apply(request.Audit, "audit", &policy.Audit); err != nil {
		httpx.Error(w, r, err)
		return
	}
	if err := apply(request.Backups, "backups", &policy.Backups); err != nil {
		httpx.Error(w, r, err)
		return
	}
	if err := apply(request.Logs, "logs", &policy.Logs); err != nil {
		httpx.Error(w, r, err)
		return
	}
	payload, _ := json.Marshal(policy)
	actor := auth.MustUser(r.Context()).ID
	if _, err := s.db.Pool.Exec(r.Context(), `
		insert into settings (key, value, updated_by) values ($1, $2::jsonb, nullif($3, '')::uuid)
		on conflict (key) do update set value = excluded.value, updated_by = excluded.updated_by, updated_at = now()`,
		retentionSettingKey, string(payload), actor); err != nil {
		httpx.Error(w, r, err)
		return
	}
	s.record(r, "retention.updated", "settings", retentionSettingKey, map[string]any{
		"tasks": policy.Tasks, "events": policy.Events, "audit": policy.Audit,
		"backups": policy.Backups, "logs": policy.Logs,
	})
	httpx.JSON(w, r, http.StatusOK, s.retentionResponse(r.Context()))
}
